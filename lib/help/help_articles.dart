/// 文章正文去掉 Markdown / LaTeX / 特殊块后的纯文本（用于搜索和摘要）。
String helpPlainText(String body) => body
    .replaceAll(RegExp(r'\[\[img:[^\]]*\]\]'), '')
    .replaceAll('[[contact]]', '联系作者 QQ $authorQQ 问题反馈')
    .replaceAll(RegExp(r'[#>*`|$]'), '')
    .replaceAll(RegExp(r'-{3,}'), '')
    .replaceAll(RegExp(r'[ \t]+'), ' ');

class HelpHit {
  final HelpArticle article;
  final String snippet; // 命中处附近的一段文字
  final int score;
  HelpHit(this.article, this.snippet, this.score);
}

/// 在全部文章中搜索：空格分隔的每个词都要出现（标题、摘要、关键词、正文），标题命中优先。
List<HelpHit> searchHelp(String query) {
  final words = query.trim().toLowerCase().split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
  if (words.isEmpty) return [];
  final out = <HelpHit>[];
  for (final a in helpArticles) {
    final plain = helpPlainText(a.body);
    final head = '${a.title} ${a.summary} ${a.keywords.join(' ')}'.toLowerCase();
    final all = '$head ${plain.toLowerCase()}';
    if (!words.every(all.contains)) continue;
    var score = 0;
    for (final w in words) {
      if (a.title.toLowerCase().contains(w)) score += 10;
      if (head.contains(w)) score += 5;
      score += RegExp(RegExp.escape(w)).allMatches(plain.toLowerCase()).length.clamp(0, 5);
    }
    // 摘要：正文里第一个命中词附近
    final lower = plain.toLowerCase();
    var i = -1;
    for (final w in words) {
      i = lower.indexOf(w);
      if (i >= 0) break;
    }
    String snippet;
    if (i < 0) {
      snippet = a.summary;
    } else {
      final start = (i - 18).clamp(0, plain.length);
      final end = (i + 60).clamp(0, plain.length);
      snippet = '${start > 0 ? '…' : ''}${plain.substring(start, end).replaceAll('\n', ' ').trim()}${end < plain.length ? '…' : ''}';
    }
    out.add(HelpHit(a, snippet, score));
  }
  out.sort((a, b) => b.score.compareTo(a.score));
  return out;
}
